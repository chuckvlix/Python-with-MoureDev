## Tipos de datos ##
print(type(7)) # -> <class 'int'>
print(type(2.14)) # -> <class 'float'>
print(type('texto')) # -> <class 'str'>
print(type(3 + 1j)) # -> <class 'complex'>
print(type(3 == 3)) # -> <class 'bool'>
print(type(2 >= 3)) # -> <class 'bool'>
print(type([1, 2, 3])) # -> <class 'list'>
print(type((9.8, 3.14, 2.7))) # -> <class 'tuple'>
print(type({9.8, 3.14, 2.7})) # -> <class 'set'>
print(type({'name':'Micky'})) # -> <class 'dict'>

